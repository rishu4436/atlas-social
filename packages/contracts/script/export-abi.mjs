// Copies Foundry ABIs into packages/shared-types/src/abi so the apps never drift from the contracts.
import fs from "node:fs";
import path from "node:path";
const here = path.dirname(new URL(import.meta.url).pathname);
const out = path.join(here, "..", "out");
const dest = path.join(here, "..", "..", "shared-types", "src", "abi");
fs.mkdirSync(dest, { recursive: true });
const names = ["AtlasIdentityRegistry", "AtlasThesisRegistry", "AtlasReviewRegistry", "AtlasOutcomeRegistry", "AtlasPay", "MockAgentID", "MockStable"];
const index = [];
for (const n of names) {
  const j = JSON.parse(fs.readFileSync(path.join(out, `${n}.sol`, `${n}.json`), "utf8"));
  fs.writeFileSync(path.join(dest, `${n}.ts`), `// Generated by packages/contracts/script/export-abi.mjs — do not edit.\nexport const ${n}Abi = ${JSON.stringify(j.abi, null, 2)} as const;\n`);
  index.push(`export { ${n}Abi } from "./${n}.js";`);
}
fs.writeFileSync(path.join(dest, "index.ts"), index.join("\n") + "\n");
console.log("exported", names.join(", "));
