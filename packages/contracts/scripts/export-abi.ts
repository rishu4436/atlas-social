/** Copies compiled ABIs into packages/core/src/abi so the app never drifts from the contracts. */
import { artifacts } from "hardhat";
import * as fs from "fs";
import * as path from "path";

async function main() {
  const dir = path.join(__dirname, "..", "..", "core", "src", "abi");
  fs.mkdirSync(dir, { recursive: true });
  for (const name of ["AtlasIdentity", "ThesisRegistry", "OutcomeAttestor", "MockAgentID"]) {
    const a = await artifacts.readArtifact(name);
    fs.writeFileSync(path.join(dir, `${name}.ts`), `// Generated by packages/contracts/scripts/export-abi.ts — do not edit.\nexport const ${name}Abi = ${JSON.stringify(a.abi, null, 2)} as const;\n`);
    console.log(`exported ${name}`);
  }
}
main().catch((e) => {
  console.error(e);
  process.exitCode = 1;
});
